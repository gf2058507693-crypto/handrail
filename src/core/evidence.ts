import path from 'node:path';
import { readTextIfExists, tail, writeTextAtomic } from './fs.js';
import type { CommandResult, EvidenceRecord } from '../types.js';

export class EvidenceStore {
  private readonly file: string;
  private readonly root: string;

  constructor(root: string) {
    this.root = root;
    this.file = path.join(root, '.handrail', 'evidence', 'evidence.jsonl');
  }

  async record(
    input: Omit<EvidenceRecord, 'id' | 'timestamp' | 'cwd'> & {
      cwd?: string;
      timestamp?: string;
    },
  ): Promise<EvidenceRecord> {
    const record: EvidenceRecord = {
      id: `ev-${Date.now()}-${Math.random().toString(36).slice(2, 8)}`,
      timestamp: input.timestamp ?? new Date().toISOString(),
      cwd: input.cwd ?? this.root,
      ...input,
    };

    const existing = (await readTextIfExists(this.file)) ?? '';
    const lines = existing.split('\n').filter(Boolean);
    lines.push(JSON.stringify(record));
    await writeTextAtomic(this.file, `${lines.join('\n')}\n`);
    return record;
  }

  async recordCommand(
    result: CommandResult,
    kind: EvidenceRecord['kind'] = 'command',
    context: { ticket?: number; spec?: number; label?: string; headSha?: string } = {},
  ): Promise<EvidenceRecord> {
    return this.record({
      kind,
      ticket: context.ticket,
      spec: context.spec,
      command: result.command,
      cwd: result.cwd,
      exitCode: result.exitCode,
      durationMs: result.durationMs,
      stdoutTail: tail(result.stdout, 6000),
      stderrTail: tail(result.stderr, 4000),
      meta: {
        timedOut: result.timedOut,
        label: context.label,
        headSha: context.headSha,
      },
    });
  }

  async list(filter: {
    ticket?: number;
    spec?: number;
    kind?: EvidenceRecord['kind'];
  } = {}): Promise<EvidenceRecord[]> {
    const raw = await readTextIfExists(this.file);
    if (!raw) return [];
    const records: EvidenceRecord[] = [];
    for (const line of raw.split('\n')) {
      if (!line.trim()) continue;
      try {
        const record = JSON.parse(line) as EvidenceRecord;
        if (filter.ticket !== undefined && record.ticket !== filter.ticket) continue;
        if (filter.spec !== undefined && record.spec !== filter.spec) continue;
        if (filter.kind !== undefined && record.kind !== filter.kind) continue;
        records.push(record);
      } catch {
        // Ignore a partially written line rather than poisoning the whole evidence log.
      }
    }
    return records;
  }

  async checksFor(ticket: number): Promise<EvidenceRecord[]> {
    return this.list({ ticket, kind: 'check' });
  }

  async assertChecksPassed(
    ticket: number,
    requireAtLeastOne: boolean,
    headSha?: string,
    requiredCommands: string[] = [],
  ): Promise<{ ok: boolean; reason?: string }> {
    const checks = (await this.checksFor(ticket)).filter(
      (check) => headSha === undefined || check.meta?.headSha === headSha,
    );
    if (checks.length === 0 && requireAtLeastOne) {
      return {
        ok: false,
        reason: `No check commands were recorded for #${ticket}. Run "handrail implement #${ticket}" or configure checks.`,
      };
    }
    const latest = new Map<string, EvidenceRecord>();
    for (const check of checks) {
      if (check.command) latest.set(check.command, check);
    }
    const missing = requiredCommands.filter((command) => !latest.has(command));
    if (missing.length > 0) {
      return { ok: false, reason: `Missing check evidence for #${ticket}: ${missing.join(', ')}` };
    }
    const failed = [...latest.values()].filter((check) => check.exitCode !== 0);
    if (failed.length > 0) {
      return {
        ok: false,
        reason: `${failed.length} check(s) failed for #${ticket}: ${failed
          .map((check) => check.command)
          .join(', ')}`,
      };
    }
    return { ok: true };
  }

  async writeTicketReport(ticket: number): Promise<string> {
    const records = await this.list({ ticket });
    const lines: string[] = [
      `# Evidence for #${ticket}`,
      '',
      '| Time | Kind | Command | Exit | Duration |',
      '|---|---|---|---|---|',
    ];
    for (const record of records) {
      const rawCommand = record.command ?? record.meta?.label ?? record.kind;
      const command = String(rawCommand).replace(/\|/g, '\\|');
      lines.push(
        `| ${record.timestamp} | ${record.kind} | \`${command}\` | ${record.exitCode ?? '-'} | ${record.durationMs ?? '-'} ms |`,
      );
    }
    lines.push('', 'Generated by Handrail. Every row is backed by a recorded execution.', '');
    const file = path.join(this.root, '.handrail', 'evidence', `ticket-${ticket}.md`);
    await writeTextAtomic(file, lines.join('\n'));
    return file;
  }

  async summarizeCommands(ticket: number): Promise<string> {
    const records = await this.list({ ticket });
    if (records.length === 0) return '_No commands were recorded._';
    return records
      .map((record) => {
        const status = record.exitCode === 0 ? 'PASS' : `FAIL(${record.exitCode ?? '?'})`;
        return `- \`${record.command ?? record.kind}\` -> ${status}`;
      })
      .join('\n');
  }
}
